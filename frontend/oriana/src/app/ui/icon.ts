interface Drawn {
  solid: string;
  light: string;
}

const drawn = new Map<IconName, Drawn>();

/** One path per tone, each a run of whole pixels: crisp at any size. */
function draw(name: IconName): Drawn {
  let paths = drawn.get(name);
  if (paths) return paths;
  const rows = PICTURES[name];
  // Centred up and down in the twelve rows.
  const top = Math.floor((12 - rows.length) / 2);
  const runs = { '#': '', '+': '' };
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch !== '#' && ch !== '+') {
        x++;
        continue;
      }
      let end = x;
      while (row[end] === ch) end++;
      runs[ch] += `M${x} ${y + top}h${end - x}v1h${x - end}z`;
      x = end;
    }
  });
  paths = { solid: runs['#'], light: runs['+'] };
  drawn.set(name, paths);
  return paths;
}

@Component({
  selector: 'app-icon',
  template: `
    <svg viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true" focusable="false">
      <path [attr.d]="paths().light" fill="currentColor" opacity="0.4" />
      <path [attr.d]="paths().solid" fill="currentColor" />
    </svg>
  `,
  styles: `
    :host {
      display: inline-block;
      flex: none;
      width: 1.25rem;
      height: 1.25rem;
    }

    svg {
      width: 100%;
      height: 100%;
      overflow: visible;
    }
  `,
})
export class Icon {
  readonly name = input.required<IconName>();
  protected readonly paths = computed(() => draw(this.name()));
}
